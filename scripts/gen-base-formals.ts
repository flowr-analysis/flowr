/**
 * Records the formals R declares for every function of a base package that flowR defines a built-in for, as
 * `package -> name -> formals`. Primitives are read through `args`, functions without formals are left out.
 * Needs an `Rscript`, writes `src/data/r-base-formals.generated.ts`.
 */
import fs from 'fs';
import path from 'path';
import { execFileSync } from 'child_process';
import { WrittenBuiltinDefinitions } from '../src/dataflow/environments/default-builtin-config';
import { Identifier, PkgName } from '../src/dataflow/environments/identifier';

const BasePackages = new Set(['base', 'stats', 'utils', 'graphics', 'grDevices', 'methods', 'tools', 'parallel', 'grid', 'splines', 'stats4', 'tcltk']);

const Reader = `
for (l in readLines("stdin")) {
  p <- strsplit(l, "\\t")[[1]]
  f <- tryCatch({ suppressMessages(library(p[1], character.only = TRUE)); get(p[2], envir = asNamespace(p[1])) }, error = function(e) NULL)
  if (!is.function(f)) next
  fm <- if (is.primitive(f)) { a <- args(f); if (is.null(a)) NULL else names(formals(a)) } else names(formals(f))
  if (!is.null(fm)) cat(p[1], p[2], paste(fm, collapse = ","), "\\n", sep = "\\t")
}`;

const wanted = new Set<string>();
for(const def of WrittenBuiltinDefinitions) {
	if(def.type === 'function') {
		for(const id of def.names as readonly Identifier[]) {
			const pkg = String(Identifier.getNamespace(id) ?? PkgName.Base);
			if(BasePackages.has(pkg)) {
				wanted.add(`${pkg}\t${Identifier.getName(id)}`);
			}
		}
	}
}
const output = execFileSync('Rscript', ['-e', Reader], { input: [...wanted].join('\n'), encoding: 'utf8', maxBuffer: 1 << 26 });
const table: Record<string, Record<string, string>> = {};
for(const line of output.split('\n').filter(Boolean)) {
	const [pkg, name, formals] = line.split('\t');
	(table[pkg] ??= {})[name] = formals;
}
const version = execFileSync('Rscript', ['-e', 'cat(as.character(getRversion()))'], { encoding: 'utf8' });
const sorted = Object.entries(table).sort(([a], [b]) => a.localeCompare(b)).map(([pkg, names]) =>
	`\t${JSON.stringify(pkg)}: {\n${Object.entries(names).sort(([a], [b]) => a.localeCompare(b)).map(([n, f]) => `\t\t${JSON.stringify(n)}: ${JSON.stringify(f)}`).join(',\n')}\n\t}`);
fs.writeFileSync(path.join(__dirname, '..', 'src', 'data', 'r-base-formals.generated.ts'),
	`/* GENERATED by scripts/gen-base-formals.ts from R ${version}, do not edit. */
/** The formals R declares for the functions of the base packages flowR defines, as \`package -> name -> comma separated formals\`. */
export const RBaseFormals: Readonly<Record<string, Readonly<Record<string, string>>>> = {
${sorted.join(',\n')}
};
`);
