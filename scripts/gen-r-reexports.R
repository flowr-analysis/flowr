# Regenerates src/data/r-reexports.generated.ts from the R running this script:
#   Rscript scripts/gen-r-reexports.R
# It records, for every installed package, the exported functions defined in another package's namespace
# (`dplyr::%>%` is magrittr's), with the version of the package that re-exports them. flowR falls back to this
# table for a signature database that does not record re-exports itself.
q <- function(x) paste0('"', gsub('"', '\\\\"', x), '"')
entries <- character()
for (p in sort(rownames(installed.packages()))) {
  if (p == "base" || !requireNamespace(p, quietly = TRUE)) next
  re <- character()
  for (n in sort(getNamespaceExports(p))) {
    f <- tryCatch(getExportedValue(p, n), error = function(e) NULL)
    if (!is.function(f) || is.primitive(f) || !isNamespace(environment(f))) next
    origin <- getNamespaceName(environment(f))
    if (origin != p && origin != "base") re[n] <- origin
  }
  if (length(re) == 0) next
  pairs <- paste0(q(names(re)), ": ", q(re), collapse = ", ")
  entries <- c(entries, paste0("\t", q(p), ": { version: ", q(as.character(packageVersion(p))), ", reexports: { ", pairs, " } }"))
}
out <- c(
  "/* eslint-disable */",
  "/*",
  paste0(" * GENERATED by scripts/gen-r-reexports.R with ", R.version.string, " -- do not edit."),
  " * Per package, at the version installed then, the exported functions it re-exports, each with the package defining it.",
  " */",
  "export const RReexports: Readonly<Record<string, { readonly version: string, readonly reexports: Readonly<Record<string, string>> }>> = {",
  paste(entries, collapse = ",\n"),
  "};",
  ""
)
writeLines(out, file.path("src", "data", "r-reexports.generated.ts"))
