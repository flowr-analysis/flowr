# Regenerates src/data/r-s3-generics.generated.ts from the R running this script:
#   Rscript scripts/gen-r-s3-generics.R
# It records the S3 generics of the base packages with their exact formals (which flowR's modeled
# signatures only partially state), the formals of the group generics, and R CMD check's list of
# functions that look like S3 methods but are none (tools:::nonS3methods).
pkgs <- c("base", "stats", "utils", "graphics", "grDevices", "methods", "tools", "datasets")
generics <- character()
for (p in pkgs) {
  ns <- asNamespace(p)
  for (n in getNamespaceExports(ns)) {
    f <- get(n, envir = ns)
    if (is.function(f) && !is.primitive(f) && "UseMethod" %in% all.names(body(f))) generics <- c(generics, n)
  }
}
generics <- sort(unique(c(generics, names(.knownS3Generics), tools:::.get_internal_S3_generics())))
formalsOf <- function(n) {
  f <- tryCatch(args(get(n, mode = "function", envir = baseenv())), error = function(e) NULL)
  if (is.null(f)) f <- tryCatch(args(getFromNamespace(n, .knownS3Generics[[n]] %||% "base")), error = function(e) NULL)
  if (is.null(f)) character() else names(formals(f))
}
q <- function(x) paste0('"', gsub('"', '\\\\"', x), '"')
line <- function(n, xs) paste0("\t\t", q(n), ": [", paste(q(xs), collapse = ", "), "]")
entries <- vapply(generics, function(n) line(n, formalsOf(n)), "")
groups <- list(Ops = c("e1", "e2"), Math = c("x", "..."), Summary = c("...", "na.rm"), Complex = c("z"), matrixOps = c("x", "y"))
# the stop list is the first expression of tools:::nonS3methods; evaluating it gives every package's entries
stopList <- eval(body(tools:::nonS3methods)[[2L]][[3L]])
out <- c(
  "/* eslint-disable */",
  "/*",
  paste0(" * GENERATED by scripts/gen-r-s3-generics.R with ", R.version.string, " -- do not edit."),
  " * genericFormals: the S3 generics of the base packages with the formals R reports for them.",
  " * groupGenericFormals: the formals of the S3 group generics (see ?groupGeneric).",
  " * nonS3Methods: per package, functions that look like S3 methods but are none (tools:::nonS3methods).",
  " */",
  "export const RS3Generics: {",
  "\treadonly genericFormals:      Readonly<Record<string, readonly string[]>>;",
  "\treadonly groupGenericFormals: Readonly<Record<string, readonly string[]>>;",
  "\treadonly nonS3Methods:        Readonly<Record<string, readonly string[]>>;",
  "} = {",
  "\tgenericFormals: {",
  paste(entries, collapse = ",\n"),
  "\t},",
  "\tgroupGenericFormals: {",
  paste(vapply(names(groups), function(n) line(n, groups[[n]]), ""), collapse = ",\n"),
  "\t},",
  "\tnonS3Methods: {",
  paste(vapply(sort(names(stopList)), function(n) line(n, stopList[[n]]), ""), collapse = ",\n"),
  "\t}",
  "};"
)
writeLines(out, "src/data/r-s3-generics.generated.ts")
