import fs from 'fs';
import { compressToBase64 } from 'lz-string';
import type { Packed } from '../src/data/packed';

/** Packs the value for `unpack` of `src/data/packed.ts`, storing each distinct part once. */
export function pack(value: unknown): Packed {
	const nodes: Packed[number][] = [];
	const known = new Map<string, number>();
	const intern = (node: Packed[number]): number => {
		const key = JSON.stringify(node);
		let i = known.get(key);
		if(i === undefined) {
			i = nodes.push(node) - 1;
			known.set(key, i);
		}
		return i;
	};
	const visit = (v: unknown): number => {
		if(Array.isArray(v)) {
			return intern(v.map(visit));
		} else if(v !== null && typeof v === 'object') {
			const entries = Object.entries(v).filter(([, e]) => e !== undefined);
			return intern([-1 - visit(entries.map(([k]) => k)), ...entries.map(([, e]) => visit(e))]);
		}
		return intern(v as Packed[number]);
	};
	visit(value);
	return nodes;
}

/** The data for `unpacked` of `src/data/packed.ts`, the value or its packed table, whichever compresses smaller. */
function compressed(value: unknown): string {
	const packed = 'p' + compressToBase64(JSON.stringify(pack(value)));
	const raw = 'r' + compressToBase64(JSON.stringify(value));
	return packed.length < raw.length ? packed : raw;
}

/** A generated export with name, documentation, type and value. Strings are written as they are, other values are decompressed on first use. */
export interface PackedExport {
	readonly name:  string
	readonly doc:   string
	readonly type:  string
	readonly value: unknown
}

/** Writes a generated data file, one line for each export, the type imports given as `import type ...` lines. */
export function writePacked(target: string, by: string, imports: readonly string[], exports: readonly PackedExport[]): void {
	fs.writeFileSync(target, [
		`/* GENERATED by ${by}, do not edit. */`,
		"import { unpacked } from './packed';",
		...imports,
		...exports.flatMap(({ name, doc, type, value }) => [`/** ${doc} */`, typeof value === 'string'
			? `export const ${name}: ${type} = ${JSON.stringify(value)};`
			: `export const ${name}: () => ${type} = unpacked('${compressed(value)}');`]),
		''
	].join('\n'));
}
