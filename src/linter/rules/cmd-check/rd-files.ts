const Always = Number.POSITIVE_INFINITY;
const NameChars = /[A-Za-z][A-Za-z0-9]*/y;

/** Reads an Rd source into a tree, noting what the lexer of `R CMD check` would complain about. */
class RdParser {
	public readonly diags: RdDiagnostic[] = [];
	private pos = 0;
	private line = 1;
	private ended = false;

	constructor(private readonly src: string, public readonly macros: Map<string, number>, private readonly lenient: boolean) {}

	public parse(): RdNode[] {
		return this.seq('text', false, undefined, 1);
	}

	private diag(line: number, kind: RdFilesKind, text: string): void {
		this.diags.push({ line, level: Always, kind, text });
	}

	private seq(mode: Mode, closing: boolean, parent: string | undefined, openLine: number): RdNode[] {
		const nodes: RdNode[] = [];
		const src = this.src;
		let buf = '';
		let bufLine = this.line;
		let quote: string | undefined;
		let quoteLine = 0;
		let comment = false;
		const flush = () => {
			if(buf !== '') {
				nodes.push({ type: 'text', text: buf, line: bufLine, mode });
				buf = '';
			}
		};
		const add = (s: string) => {
			if(buf === '') {
				bufLine = this.line;
			}
			buf += s;
		};
		while(this.pos < src.length) {
			const c = src[this.pos];
			if(c === '\n') {
				add(c);
				this.pos++;
				flush();
				this.line++;
				comment = false;
				continue;
			} else if(c === '%') {
				flush();
				const eol = src.indexOf('\n', this.pos);
				this.pos = eol < 0 ? src.length : eol + 1;
				this.line += eol < 0 ? 0 : 1;
				comment = false;
				continue;
			} else if(c === '\\') {
				const n = src[this.pos + 1];
				if(n !== undefined && '\\%{}'.includes(n)) {
					add(c + n);
					this.pos += 2;
				} else if(quote !== undefined) {
					add(c);
					this.pos++;
					if(n !== undefined && n !== '\n') {
						add(n);
						this.pos++;
					}
				} else if(mode !== 'verb' && !comment && n !== undefined && /[A-Za-z]/.test(n)) {
					flush();
					this.macro(nodes, parent);
				} else {
					add(c);
					this.pos++;
				}
				continue;
			} else if(c === '{' && quote === undefined) {
				flush();
				const line = this.line;
				this.pos++;
				nodes.push({ type: 'group', children: this.seq(mode, true, parent, line), line });
				continue;
			} else if(c === '}' && quote === undefined) {
				this.pos++;
				if(closing) {
					flush();
					return nodes;
				}
				this.diag(this.line, 'rd-syntax', 'unexpected \'}\'');
				continue;
			} else if(mode === 'rlike') {
				if(quote !== undefined) {
					quote = c === quote ? undefined : quote;
				} else if(!comment) {
					if(c === '#') {
						comment = true;
					} else if(c === '"' || c === '\'' || c === '`') {
						quote = c;
						quoteLine = this.line;
					}
				}
			}
			add(c);
			this.pos++;
		}
		flush();
		if(!this.ended && (quote !== undefined || closing)) {
			this.ended = true;
			this.diag(quote !== undefined ? quoteLine : openLine, 'rd-syntax', quote !== undefined
				? `Unexpected end of input (in ${quote} quoted string opened at line ${quoteLine})`
				: `unexpected END_OF_INPUT (the '{' on line ${openLine} is never closed)`);
		}
		return nodes;
	}

	private specOf(name: string, parent: string | undefined): MacroSpec | undefined {
		if(name === 'item') {
			return parent === 'arguments' || parent === 'value' || parent === 'describe' ? t2 : parent === 'itemize' || parent === 'enumerate' ? none : undefined;
		}
		const known = Macros.get(name);
		if(known !== undefined) {
			return known;
		}
		const arity = this.macros.get(name);
		return arity === undefined ? undefined : { modes: 't'.repeat(arity), min: arity };
	}

	private skipSpace(): void {
		while(this.pos < this.src.length && /\s/.test(this.src[this.pos])) {
			if(this.src[this.pos] === '\n') {
				this.line++;
			}
			this.pos++;
		}
	}

	private macro(nodes: RdNode[], parent: string | undefined): void {
		const line = this.line;
		this.pos++;
		NameChars.lastIndex = this.pos;
		const name = NameChars.exec(this.src)?.[0] ?? '';
		this.pos += name.length;
		const spec = this.specOf(name, parent);
		if(spec === undefined) {
			if(!this.lenient) {
				this.diag(line, 'rd-unknown-macro', `unknown macro '\\${name}'`);
			}
			const consumed: RdNode[][] = [];
			while(this.src[this.pos] === '{') {
				const open = this.line;
				this.pos++;
				consumed.push(this.seq('text', true, parent, open));
				if(!this.lenient) {
					break;
				}
			}
			if(this.lenient) {
				nodes.push({ type: 'macro', name, line, args: consumed });
			}
			return;
		}
		let option: string | undefined;
		if((name === 'link' || name === 'Sexpr') && this.src[this.pos] === '[') {
			const close = this.src.indexOf(']', this.pos);
			if(close > 0) {
				option = this.src.slice(this.pos + 1, close);
				this.line += option.split('\n').length - 1;
				this.pos = close + 1;
			}
		}
		const args: RdNode[][] = [];
		let body: RdMacro['body'];
		for(let i = 0; i < spec.modes.length; i++) {
			if(i < spec.min) {
				const save = { pos: this.pos, line: this.line };
				if(i > 0) {
					this.skipSpace();
				}
				if(this.src[this.pos] !== '{') {
					const spaced = i === 0 && /^\s+\{/.test(this.src.slice(save.pos, save.pos + 8));
					if(i > 0 || spaced) {
						this.diag(this.line, 'rd-syntax', 'bad markup (extra space?)');
					}
					this.pos = i > 0 ? this.pos : save.pos;
					break;
				}
			} else if(this.src[this.pos] !== '{') {
				break;
			}
			const open = this.line;
			this.pos++;
			const from = this.pos;
			const mode: Mode = spec.modes[i] === 'v' ? 'verb' : spec.modes[i] === 'r' ? 'rlike' : 'text';
			args.push(this.seq(mode, true, name, open));
			if(i === 0) {
				body = { from, to: this.pos - 1, line: open };
			}
		}
		if((name === 'newcommand' || name === 'renewcommand') && args.length === 2) {
			const defined = /\\([A-Za-z][A-Za-z0-9]*)/.exec(plain(args[0]));
			if(defined !== null) {
				const params = [...deparse(args[1]).matchAll(/#(\d)/g)].map(m => Number(m[1]));
				this.macros.set(defined[1], Math.max(0, ...params));
			}
		}
		nodes.push({ type: 'macro', name, line, option, args, body });
	}
}

/** the raw text of the text nodes, macros skipped */
function plain(nodes: readonly RdNode[]): string {
	return nodes.map(n => n.type === 'text' ? n.text : n.type === 'group' ? plain(n.children) : '').join('');
}

/** the source form of a node list, as `.Rd_deparse` gives it */
function deparse(nodes: readonly RdNode[]): string {
	return nodes.map(n => {
		switch(n.type) {
			case 'text':  return n.text;
			case 'group': return `{${deparse(n.children)}}`;
			default:      return `\\${n.name}${n.args.map(a => `{${deparse(a)}}`).join('')}`;
		}
	}).join('');
}

/** whether the nodes hold no text at all, as `prepare_Rd` decides what an empty section is */
function isBlank(nodes: readonly RdNode[]): boolean {
	return nodes.every(n => n.type === 'text' ? !/\S/.test(n.text) : n.type === 'group' ? isBlank(n.children) : Macros.has(n.name) && n.args.every(isBlank));
}

/** `isBlankRd` on an item label: any markup element counts as content */
const isBlankLabel = (nodes: readonly RdNode[]) => nodes.every(n => n.type === 'text' && !/\S/.test(n.text));

