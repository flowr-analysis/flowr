/** The checks of `tools::checkRd` and the structure checks of `prepare_Rd`, run on one page. */
class RdChecker {
	public readonly diags: RdDiagnostic[] = [];
	public readonly links: RdLink[] = [];
	private hasText = false;
	private defEnc:        boolean;
	private inEnc2 = false;

	constructor(private readonly settings: PageSettings) {
		this.defEnc = settings.defEnc;
	}

	private warn(line: number, level: number, kind: RdFilesKind, text: string): void {
		this.diags.push({ line, level, kind, text });
	}

	public sections(nodes: readonly RdNode[]): { name: string | undefined, nameLine: number, docType: string, fatal: boolean } {
		const macros = nodes.filter((n): n is RdMacro => n.type === 'macro');
		for(const n of nodes) {
			if(n.type === 'text' && /[^\s]/.test(n.text)) {
				this.warn(n.line, Always, 'rd-structure', 'All text must be in a section');
			}
		}
		const versions = macros.filter(m => m.name === 'Rdversion');
		if(versions.length > 1) {
			this.warn(versions[1].line, Always, 'rd-structure', 'Only one \\Rdversion declaration is allowed');
		}
		const kept: RdMacro[] = [];
		for(const m of macros) {
			if(SectionNames.has(m.name)) {
				kept.push(m);
			} else if(!ExtraSections.has(m.name) && !this.settings.macros.has(m.name) && !this.settings.lenient) {
				this.warn(m.line, Always, 'rd-structure', `unexpected macro '\\${m.name}'`);
			}
		}
		const docTypes = macros.filter(m => m.name === 'docType');
		if(docTypes.length > 1) {
			this.warn(docTypes[1].line, Always, 'rd-structure', 'Multiple \\docType sections are not supported');
		}
		for(const d of docTypes) {
			const type = plain(d.args[0] ?? []).trim();
			if(!DocTypes.has(type)) {
				this.warn(d.line, Always, 'rd-structure', `docType '${type}' is unrecognized`);
			}
		}
		const docType = docTypes.length > 0 ? plain(docTypes[0].args[0] ?? []).trim() : '';
		const dropped = new Set<RdMacro>();
		for(const tag of UniqueSections) {
			for(const dup of kept.filter(m => m.name === tag).slice(1)) {
				this.warn(dup.line, Always, 'rd-structure', `Only one \\${tag} section is allowed: the first will be used`);
				dropped.add(dup);
			}
		}
		if(kept.some(m => m.name === 'encoding')) {
			this.defEnc = true;
		}
		const names = kept.filter(m => m.name === 'name');
		const titles = kept.filter(m => m.name === 'title');
		if(names.length !== 1 || titles.length !== 1) {
			this.warn(1, Always, 'rd-structure', 'Sections \\title, and \\name must exist and be unique in Rd files');
			return { name: undefined, nameLine: 1, docType, fatal: true };
		}
		const nameText = unescape(plain(names[0].args[0] ?? []));
		if(nameText.trim() === '' || nameText.includes('\\') || (names[0].args[0] ?? []).some(n => n.type !== 'text')) {
			this.warn(names[0].line, Always, 'rd-structure', '\\name must only contain simple text');
			return { name: undefined, nameLine: names[0].line, docType, fatal: true };
		}
		const name = nameText.trim();
		if(/[!|@]/.test(name)) {
			this.warn(names[0].line, 5, 'rd-markup', '\\name should not contain !, | or @');
		}
		if(/[^\x20-\x7e]/.test(name)) {
			this.warn(names[0].line, -1, 'rd-markup', '\\name should only contain printable ASCII characters');
		}
		for(const m of kept) {
			if(!dropped.has(m)) {
				this.section(m);
			}
		}
		return { name, nameLine: names[0].line, docType, fatal: false };
	}

	private section(m: RdMacro): void {
		const tagTitle = m.name === 'section' ? `'${plain(m.args[0] ?? []).trim()}'` : `\\${m.name}`;
		const content = m.name === 'section' ? m.args[1] ?? [] : m.args[0] ?? [];
		if(isBlank(content)) {
			this.warn(m.line, Always, 'rd-empty-section', `Dropping empty section ${tagTitle}`);
			return;
		}
		this.checkSection(m, tagTitle);
	}

	private checkSection(m: RdMacro, tagTitle: string): void {
		const titled = m.name === 'section' || m.name === 'subsection';
		const title = titled ? m.args[0] ?? [] : [];
		const content = titled ? m.args[1] ?? [] : m.args[0] ?? [];
		if(titled) {
			this.content(title, m.name, m.name);
		}
		this.hasText = false;
		if(CodeBlocks.has(m.name)) {
			this.code(content, m.name);
		} else {
			this.content(content, m.name, m.name);
		}
		if(!this.hasText) {
			this.warn(m.line, 3, 'rd-empty-section', `Empty section ${tagTitle}`);
		}
		if(m.name === 'title' || titled) {
			const rd = deparse(m.name === 'title' ? content : title);
			if(/[^.]\.\s*$/.test(rd) && !/(etc|et\s+al)\.\s*$/.test(rd)) {
				this.warn(m.line, -5, 'rd-markup', `\\${m.name}${m.name === 'title' ? '' : ' name'} should not end in a period`);
			}
		}
	}

	private text(n: RdText): void {
		if(!/\S/.test(n.text)) {
			return;
		}
		this.hasText = true;
		if((this.inEnc2 || !this.defEnc) && /\P{ASCII}/u.test(n.text)) {
			this.warn(n.line, -1, 'rd-encoding', `Non-ASCII contents ${this.inEnc2 ? 'in second part of \\enc' : 'without declared encoding'}: '${n.text.trim()}'`);
		}
		if(n.mode === 'text') {
			const specials = [...n.text.matchAll(/(?:^|[^\\])(\\[#$&_^~])/g)].map(m => m[1]);
			if(specials.length > 0) {
				this.warn(n.line, -1, 'rd-markup', `Escaped LaTeX specials: ${specials.join(' ')}`);
			}
		}
	}

	private content(nodes: readonly RdNode[], blocktag: string, sectionTag: string): void {
		nodes.forEach((n, i) => {
			if(n.type === 'text') {
				this.text(n);
			} else if(n.type === 'group') {
				if(n.children.length > 0 && !isBlank(n.children)) {
					this.lostBraces(n, nodes.slice(0, i), blocktag, sectionTag);
				}
				this.content(n.children, blocktag, sectionTag);
			} else if(n.name === 'item') {
				if((blocktag === 'arguments' || blocktag === 'value' || blocktag === 'describe') && isBlankLabel(n.args[0] ?? [])) {
					this.warn(n.line, 5, 'rd-markup', `\\item in \\${blocktag} must have non-empty label`);
				}
				this.content(n.args[0] ?? [], 'item', sectionTag);
				this.content(n.args[1] ?? [], 'item', sectionTag);
			} else {
				this.block(n, blocktag, sectionTag);
			}
		});
	}

	private lostBraces(group: RdGroup, pre: readonly RdNode[], blocktag: string, sectionTag: string): void {
		const tagOf = (n: RdNode) => n.type === 'text' ? (/^\s*$/.test(n.text) ? 'BLANK' : 'TEXT') : n.type === 'group' ? 'LIST' : `\\${n.name}`;
		const pretags = pre.map(tagOf);
		const nonBlank = pretags.filter(t => t !== 'BLANK');
		if(nonBlank.length === 0) {
			return;
		}
		const pretag = nonBlank[nonBlank.length - 1];
		const preblock = pre[pre.length - 1];
		const tags = group.children.map(tagOf);
		const inItemize = blocktag === 'itemize' || blocktag === 'enumerate';
		const last = pretags[pretags.length - 1];
		const separated = pretags.length === 0 || last === 'BLANK' || (last === 'TEXT' && preblock.type === 'text' && !/([A-Za-z0-9]|\\[!-/:-@[-`{-~]|[\])])$/.test(preblock.text));
		const ignore = (tags.length === 1 && tags[0].startsWith('\\') && separated) || (inItemize && pretag === '\\item') || pretag === '\\tab'
			|| ((sectionTag === 'source' || sectionTag === 'references') && (separated || pretag === '\\cr'));
		if(ignore) {
			return;
		}
		const hint = separated && tags.length === 1 && tags[0] === 'TEXT' ? '; missing escapes or markup?' : '';
		this.warn(group.line, -1, 'rd-lost-braces', `Lost braces${hint}`);
	}

	private checkLink(m: RdMacro): void {
		this.content(m.args[0] ?? [], m.name, m.name);
		const text = plain(m.args[0] ?? []).trim();
		const option = m.option?.trim();
		let topic = text;
		if(m.name === 'linkS4class') {
			topic += '-class';
		} else if(m.name === 'linkS4methods') {
			topic += '-methods';
		}
		if(option === undefined || option === '') {
			this.links.push({ line: m.line, topic, pkg: undefined, shown: `\\${m.name}{${text}}` });
		} else if(option.startsWith('=')) {
			this.links.push({ line: m.line, topic: option.slice(1), pkg: undefined, shown: `\\${m.name}[${option}]{${text}}` });
		} else if(option.includes(':')) {
			const [pkg, file] = [option.slice(0, option.indexOf(':')), option.slice(option.indexOf(':') + 1)];
			this.links.push({ line: m.line, topic: file, pkg, shown: `\\${m.name}[${option}]{${text}}` });
		} else {
			this.links.push({ line: m.line, topic: text, pkg: option, shown: `\\${m.name}[${option}]{${text}}` });
		}
	}

	private checkUrl(m: RdMacro): void {
		const url = unescape(plain(m.args[0] ?? [])).replace(/\s+/g, '').trim();
		const scheme = /^([A-Za-z][A-Za-z0-9+.-]*):/.exec(url)?.[1];
		if(scheme === undefined) {
			return;
		}
		if(!this.settings.urlSchemes.has(scheme.toLowerCase()) || (scheme.toLowerCase() === 'mailto' && !EmailPattern.test(url.slice('mailto:'.length)))) {
			this.warn(m.line, 7, 'rd-markup', `Invalid URL: ${url}`);
		}
	}

	private block(m: RdMacro, blocktag: string, sectionTag: string): void {
		const name = m.name;
		if(PlainContentMacros.has(name) && !PlainCodeMacros.has(name)) {
			m.args.forEach(a => this.content(a, name, sectionTag));
		} else if(PlainCodeMacros.has(name)) {
			this.code(m.args[0] ?? [], name);
		} else if(LinkMacros.has(name)) {
			this.checkLink(m);
		} else if(name === 'email') {
			const address = unescape(plain(m.args[0] ?? [])).trim();
			if(address !== '' && !EmailPattern.test(address)) {
				this.warn(m.line, 7, 'rd-markup', `Invalid email address: ${address}`);
			}
			this.hasText = true;
		} else if(name === 'url') {
			this.checkUrl(m);
			this.hasText = true;
		} else if(name === 'cr' || name === 'newcommand' || name === 'renewcommand' || name === 'out') {
			return;
		} else if(name === 'dots' || name === 'ldots' || name === 'R' || SystemMacros.has(name) || this.settings.macros.has(name) || this.settings.lenient) {
			this.hasText = true;
			m.args.forEach(a => this.content(a, name, sectionTag));
		} else if(name === 'method' || name === 'S3method' || name === 'S4method') {
			this.warn(m.line, 7, 'rd-markup', `Tag \\${name} not valid outside a code block`);
		} else if(name === 'enc') {
			this.content(m.args[0] ?? [], name, sectionTag);
			const saved = this.defEnc;
			this.defEnc = false;
			this.inEnc2 = true;
			this.content(m.args[1] ?? [], name, sectionTag);
			this.defEnc = saved;
			this.inEnc2 = false;
		} else if(name === 'eqn' || name === 'deqn' || name === 'figure') {
			this.content(m.args[0] ?? [], name, sectionTag);
			if(m.args[1] !== undefined) {
				this.content(m.args[1], name, sectionTag);
				const options = plain(m.args[1]);
				if(options.startsWith('options: ') && /(height|width) *= *['"]?[0-9]+%/.test(options)) {
					this.warn(m.line, -1, 'rd-markup', 'height/width attributes should be in pixels');
				}
			}
		} else if(name === 'tabular') {
			this.tabular(m);
		} else if(name === 'subsection') {
			this.checkSection(m, `'${plain(m.args[0] ?? []).trim()}'`);
			this.hasText = true;
		} else if(name === 'if' || name === 'ifelse') {
			const formats = plain(m.args[0] ?? []).split(',').map(s => s.trim()).filter(f => !['', 'latex', 'example', 'text', 'html', 'TRUE', 'FALSE'].includes(f));
			if(formats.length > 0) {
				this.warn(m.line, 7, 'rd-markup', `Unrecognized format: ${formats.join(' ')}`);
			}
			this.content(m.args[1] ?? [], name, sectionTag);
			if(name === 'ifelse') {
				this.content(m.args[2] ?? [], name, sectionTag);
			}
		} else if(name === 'href') {
			this.checkUrl(m);
			this.content(m.args[1] ?? [], name, sectionTag);
		} else {
			this.warn(m.line, 7, 'rd-markup', `Tag \\${name} not recognized`);
		}
	}

	private code(nodes: readonly RdNode[], blocktag: string): void {
		for(const n of nodes) {
			if(n.type === 'text') {
				this.text(n);
			} else if(n.type === 'group') {
				this.code(n.children, blocktag);
			} else if(n.name === 'var' || n.name === 'special') {
				this.code(n.args[0] ?? [], blocktag);
			} else if(n.name === 'dots' || n.name === 'R' || n.name === 'newcommand' || n.name === 'renewcommand' || n.name === 'Sexpr' || this.settings.macros.has(n.name) || this.settings.lenient) {
				this.hasText = true;
			} else if(n.name === 'ldots') {
				this.warn(n.line, -3, 'rd-markup', 'Tag \\ldots is invalid in a code block');
				this.hasText = true;
			} else if(LinkMacros.has(n.name)) {
				this.checkLink(n);
			} else if(n.name === 'method' || n.name === 'S3method' || n.name === 'S4method') {
				if(blocktag === 'usage') {
					n.args.forEach(a => this.content(a, n.name, blocktag));
				} else {
					this.warn(n.line, 7, 'rd-markup', `Tag \\${n.name} is only valid in \\usage`);
				}
			} else if(ExampleWrappers.has(n.name)) {
				if(blocktag === 'examples') {
					this.code(n.args[0] ?? [], blocktag);
				} else {
					this.warn(n.line, 7, 'rd-markup', `Tag \\${n.name} is only valid in \\examples`);
				}
			} else {
				this.warn(n.line, 7, 'rd-markup', `Tag \\${n.name} is invalid in a \\${blocktag} block`);
				this.hasText = true;
			}
		}
	}

	private tabular(table: RdMacro): void {
		this.hasText = true;
		const format = table.args[0] ?? [];
		const content = [...(table.args[1] ?? [])];
		if(format.length !== 1 || format[0].type !== 'text') {
			this.warn(table.line, 7, 'rd-markup', '\\tabular format must be simple text');
		}
		const spec = plain(format).trim();
		if(!/^[lcr]*$/.test(spec)) {
			this.warn(table.line, 7, 'rd-markup', `Unrecognized \\tabular format: ${spec}`);
		}
		const lastCr = content.map(n => n.type === 'macro' && n.name === 'cr').lastIndexOf(true);
		if(lastCr >= 0 && isBlank(content.slice(lastCr + 1))) {
			content.splice(lastCr, 1);
		}
		const len = spec.length;
		let col = 1;
		let row = 1;
		const check = (c: number) => {
			if(c !== len) {
				this.warn(table.line, c > len ? 7 : -2, 'rd-markup', `Only ${len} ${len === 1 ? 'column' : 'columns'} allowed in this table (row ${row} has ${c})`);
			}
		};
		content.forEach((n, i) => {
			if(n.type === 'macro' && n.name === 'cr') {
				check(col);
				row++;
				col = 1;
			} else if(n.type === 'macro' && n.name === 'tab') {
				col++;
			} else if(n.type === 'text') {
				this.text(n);
			} else if(n.type === 'group') {
				this.lostBraces(n, content.slice(0, i), 'tabular', 'tabular');
				this.content(n.children, 'tabular', 'tabular');
			} else {
				this.block(n, 'tabular', 'tabular');
			}
		});
		check(col);
	}
}

/** the first top-level macro of a page with this name, `undefined` if there is none */
function sectionOf(nodes: readonly RdNode[], name: string): RdMacro | undefined {
	return nodes.find((n): n is RdMacro => n.type === 'macro' && n.name === name);
}

function sectionsOf(nodes: readonly RdNode[], name: string): RdMacro[] {
	return nodes.filter((n): n is RdMacro => n.type === 'macro' && n.name === name);
}

/** Reads and checks one Rd page. */
function checkPage(file: string, src: string, settings: PageSettings): RdPage {
	const parser = new RdParser(src, new Map(settings.macros), settings.lenient);
	const nodes = parser.parse();
	const checker = new RdChecker({ ...settings, macros: parser.macros });
	const diags: RdDiagnostic[] = [...parser.diags];
	const fatalSyntax = parser.diags.some(d => d.kind === 'rd-syntax');
	let info: ReturnType<RdChecker['sections']> = { name: undefined, nameLine: 1, docType: '', fatal: true };
	if(!fatalSyntax) {
		info = checker.sections(nodes);
		diags.push(...checker.diags);
	}
	const aliases = sectionsOf(nodes, 'alias').map(a => unescape(plain(a.args[0] ?? [])).trim()).filter(a => a !== '');
	const keywords = sectionsOf(nodes, 'keyword').map(k => ({ keyword: plain(k.args[0] ?? []).trim(), line: k.line }));
	return { file, name: info.name, aliases, keywords, docType: info.docType, links: checker.links, nameLine: info.nameLine, nodes, src, diags };
}

/** the lines of a code section the way the PDF manual sets them */
function renderedLines(page: RdPage, section: RdMacro): { line: number, text: string }[] {
	const body = section.body;
	if(body === undefined) {
		return [];
	}
	return page.src.slice(body.from, body.to).split('\n').map((l, i) => ({
		line: body.line + i,
		text: unescape(l.replace(/(?<!\\)%.*$/, '')).replace(/\\l?dots/g, '...').replace(/\s+$/, '')
	}));
}

const BoilerplateTitle = 'A Capitalized Title';

/** the unedited content `prompt()` and `package.skeleton()` generate */
function boilerplate(page: RdPage, includeKeywords: boolean): { line: number, section: string }[] {
	const found: { line: number, section: string }[] = [];
	const nodes = page.nodes;
	const title = sectionOf(nodes, 'title');
	if(title !== undefined && deparse(title.args[0] ?? []).trim().startsWith(BoilerplateTitle)) {
		found.push({ line: title.line, section: '\\title' });
	}
	const details = sectionOf(nodes, 'details');
	const detailsText = details === undefined ? '' : deparse(details.args[0] ?? []);
	if(details !== undefined && (detailsText.includes('If necessary, more details than the description above') || ((details.args[0] ?? []).length <= 11 && detailsText.includes('~~ An overview of how to use the package')))) {
		found.push({ line: details.line, section: '\\details' });
	}
	const args = sectionOf(nodes, 'arguments');
	for(const item of (args?.args[0] ?? []).filter((n): n is RdMacro => n.type === 'macro' && n.name === 'item')) {
		const label = plain(item.args[0] ?? []).trim();
		if(deparse(item.args[1] ?? []).trim() === `~~Describe \\code{${label}} here~~`) {
			found.push({ line: item.line, section: `\\arguments: ${label}` });
		}
	}
	const references = sectionOf(nodes, 'references');
	if(references !== undefined && /Literature or other references for background information/.test(deparse(references.args[0] ?? []).replace(/\s+/g, ' '))) {
		found.push({ line: references.line, section: '\\references' });
	}
	const seealso = sectionOf(nodes, 'seealso');
	if(seealso !== undefined && (seealso.args[0] ?? []).length <= 5 && deparse(seealso.args[0] ?? []).includes('Optional links to other man pages')) {
		found.push({ line: seealso.line, section: '\\seealso' });
	}
	const examples = sectionOf(nodes, 'examples');
	if(examples !== undefined && deparse(examples.args[0] ?? []).includes('Optional simple examples of the most important functions')) {
		found.push({ line: examples.line, section: '\\examples' });
	}
	if(includeKeywords) {
		for(const k of page.keywords.filter(k => ['~kwd1', '~kwd2', '~~ other possible keyword(s) ~~'].includes(k.keyword))) {
			found.push({ line: k.line, section: `\\keyword: ${k.keyword}` });
		}
	}
	return found;
}

/** the argument names an `\arguments` section documents with no text */
function emptyArguments(page: RdPage): { line: number, name: string }[] {
	const args = sectionOf(page.nodes, 'arguments');
	return (args?.args[0] ?? []).filter((n): n is RdMacro => n.type === 'macro' && n.name === 'item' && n.args.length === 2)
		.filter(item => isBlank(item.args[1]) && !isBlank(item.args[0]))
		.flatMap(item => plain(item.args[0]).split(',').map(s => ({ line: item.line, name: s.trim() })).filter(a => a.name !== ''));
}

/** the names called in a `\usage` outside of `\method`, one per entry */
function usageCalls(page: RdPage): { line: number, name: string }[] {
	const usage = sectionOf(page.nodes, 'usage');
	const calls: { line: number, name: string }[] = [];
	const visit = (nodes: readonly RdNode[]) => {
		for(const n of nodes) {
			if(n.type === 'text') {
				const m = /^\s*([A-Za-z.][A-Za-z0-9._]*)\s*\(/.exec(n.text);
				if(m !== null) {
					calls.push({ line: n.line, name: m[1] });
				}
			} else if(n.type === 'group') {
				visit(n.children);
			} else if(ExampleWrappers.has(n.name)) {
				visit(n.args[0] ?? []);
			}
		}
	};
	visit(usage?.args[0] ?? []);
	return calls;
}

/** the `\bibcitep`/`\bibcitet` keys a page cites but never shows with `\bibshow` */
function citedNotShown(page: RdPage): { line: number, keys: string[] } | undefined {
	const events: { name: string, keys: string[], line: number }[] = [];
	const visit = (nodes: readonly RdNode[]) => {
		for(const n of nodes) {
			if(n.type === 'group') {
				visit(n.children);
			} else if(n.type === 'macro') {
				if(n.name === 'bibcitep' || n.name === 'bibcitet' || n.name === 'bibshow') {
					events.push({ name: n.name, keys: plain(n.args[0] ?? []).split(',').map(k => k.trim()).filter(k => k !== ''), line: n.line });
				}
				n.args.forEach(visit);
			}
		}
	};
	visit(page.nodes);
	let cited: string[] = [];
	let cache: string[] = [];
	let shown: string[] = [];
	let first = 0;
	for(const e of events) {
		if(e.name !== 'bibshow') {
			cited = uniqueArrayMerge(cited, e.keys);
			cache = uniqueArrayMerge(cache, e.keys);
			first ||= e.line;
		} else if(e.keys.length === 0) {
			cited = [];
		} else {
			shown = uniqueArrayMerge(shown, e.keys.includes('*') ? [...e.keys.filter(k => k !== '*'), ...cache] : e.keys);
		}
	}
	const missing = cited.filter(k => !shown.includes(k));
	return missing.length > 0 ? { line: first, keys: missing } : undefined;
}

/** a tree-sitter error node, searched without recursion deeper than the tree */
function firstErrorRow(root: { isError: boolean, isMissing: boolean, children: readonly unknown[], startPosition: { row: number } }): number | undefined {
	const stack = [root];
	while(stack.length > 0) {
		const node = stack.pop() as typeof root;
		if(node.isError || node.isMissing) {
			return node.startPosition.row;
		}
		stack.push(...(node.children as typeof root[]).slice().reverse());
	}
	return undefined;
}

