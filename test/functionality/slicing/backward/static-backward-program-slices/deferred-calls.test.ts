import { assertSliceMatchesR, withTreeSitter } from '../../../_helper/shell';
import { describe } from 'vitest';

/** a call that decides when, where or whether its argument runs stays with the argument, one that only passes it on does not */
describe('Deferred arguments checked against R', withTreeSitter(parser => {
	const cases: readonly (readonly [name: string, code: string, dropped?: string])[] = [
		['eval expression', 'eval(expression(x <- 1, y <- x + 1))\nprint(y)'],
		['eval quote', 'eval(quote(y <- 2))\nprint(y)', 'quote'],
		['eval parse text', 'eval(parse(text = "y <- 2"))\nprint(y)'],
		['evalq', 'e <- new.env()\nevalq(y <- 2, e)\nprint(e$y)'],
		['eval bquote', 'a <- 2\neval(bquote(y <- .(a) + 1))\nprint(y)'],
		['do.call string', 'x <- 0\ninc <- function() x <<- x + 1\ndo.call("inc", list())\nprint(x)'],
		['do.call symbol', 'x <- 0\ninc <- function() x <<- x + 1\ndo.call(inc, list())\nprint(x)'],
		['do.call string args', 'f <- function(a) a * 2\ny <- do.call("f", list(4))\nprint(y)'],
		['on.exit restore', 'mk <- function(d) function() { on.exit(options(digits = 7)); options(digits = d); format(pi) }\nf3 <- mk(3)\nx <- f3()\nprint(pi)'],
		['on.exit assign global', 'x <- 0\nf <- function() { on.exit(x <<- 5); x <<- 1 }\nf()\nprint(x)'],
		['on.exit order', 'x <- 0\nf <- function() { on.exit(x <<- 5); x <<- 1; invisible() }\nf()\nprint(x)'],
		['delayedAssign', 'delayedAssign("y", {x <<- 3; 4})\nx <- 1\nprint(y)\nprint(x)'],
		['delayedAssign unforced', 'x <- 1\ndelayedAssign("y", x <<- 3)\nprint(x)'],
		['tryCatch handler', 'x <- 0\ntryCatch(stop("a"), error = function(e) x <<- 1)\nprint(x)'],
		['tryCatch finally', 'x <- 0\ntryCatch(1, finally = x <- 2)\nprint(x)'],
		['withCallingHandlers', 'x <- 0\nwithCallingHandlers(warning("w"), warning = function(w) { x <<- 1; invokeRestart("muffleWarning") })\nprint(x)'],
		['lapply fun', 'x <- 0\nlapply(1:3, function(i) x <<- x + i)\nprint(x)'],
		['sapply fun', 'x <- 0\nsapply(1:3, function(i) x <<- x + i)\nprint(x)'],
		['Map fun', 'x <- 0\nMap(function(i) x <<- x + i, 1:3)\nprint(x)'],
		['Reduce fun', 'x <- 0\nReduce(function(a, i) { x <<- x + i; a }, 1:3, 0)\nprint(x)'],
		['Filter fun', 'x <- 0\nFilter(function(i) { x <<- x + i; TRUE }, 1:3)\nprint(x)'],
		['local', 'x <- 0\nlocal({ x <<- 7 })\nprint(x)'],
		['local assign', 'y <- local({ a <- 2; a * 3 })\nprint(y)'],
		['system.time', 'x <- 0\nsystem.time(x <- 5)\nprint(x)'],
		['Recall', 'f <- function(n) if(n <= 0) 0 else n + Recall(n - 1)\ny <- f(3)\nprint(y)'],
		['reg.finalizer', 'x <- 0\ne <- new.env()\nreg.finalizer(e, function(e) x <<- 1, onexit = TRUE)\nprint(x)'],
		['invisible wrapper', 'y <- invisible(3)\nprint(y)'],
		['suppressWarnings wrapper', 'y <- suppressWarnings(as.numeric("3"))\nprint(y)'],
		['suppressWarnings assign', 'suppressWarnings(y <- as.numeric("3"))\nprint(y)', 'suppressWarnings'],
		['identity wrapper', 'x <- 1\nidentity(x <- 2)\nprint(x)', 'identity'],
		['force', 'x <- 1\nforce(x <- 2)\nprint(x)', 'force'],
		['with data', 'd <- list(a = 1)\nwith(d, y <- a + 1)\nprint(1)'],
		['with assign out', 'd <- list(a = 1)\ny <- with(d, a + 1)\nprint(y)'],
		['Reduce local', 'y <- Reduce(function(a, b) a + b, 1:3)\nprint(y)'],
		['vapply side effect', 'x <- 0\nvapply(1:3, function(i) { x <<- x + i; 1 }, numeric(1))\nprint(x)'],
		['try', 'x <- 0\ntry(x <- 3)\nprint(x)', 'try'],
		['suppressMessages side effect', 'x <- 0\nsuppressMessages(x <- 3)\nprint(x)', 'suppressMessages'],
		['quote only', 'x <- 1\nquote(x <- 5)\nprint(x)', 'quote'],
		['switch arm', 'x <- 0\nswitch("a", a = x <- 1, b = x <- 2)\nprint(x)'],
		['mapply', 'x <- 0\nmapply(function(i) x <<- x + i, 1:3)\nprint(x)'],
		['match.fun', 'x <- 0\nf <- function() x <<- 9\ng <- match.fun("f")\ng()\nprint(x)'],
		['on.exit add', 'x <- 0\nf <- function() { on.exit(x <<- x + 1, add = TRUE); on.exit(x <<- x * 10, add = TRUE); NULL }\nf()\nprint(x)'],
		['sapply fun by string', 'x <- 0\nf <- function(i) x <<- x + i\nsapply(1:3, "f")\nprint(x)'],
		['lapply fun symbol', 'x <- 0\nf <- function(i) x <<- x + i\nlapply(1:3, f)\nprint(x)'],
		['Map fun symbol', 'x <- 0\nf <- function(i) x <<- x + i\nMap(f, 1:3)\nprint(x)'],
		['Reduce fun string', 'x <- 0\nf <- function(a, i) { x <<- x + i; a }\nReduce("f", 1:3, 0)\nprint(x)'],
		['do.call named what', 'x <- 0\ninc <- function() x <<- x + 1\ndo.call(what = "inc", args = list())\nprint(x)'],
		['do.call result', 'f <- function(a, b) a - b\ny <- do.call("f", list(5, 2))\nprint(y)'],
		['tryCatch handler symbol', 'x <- 0\nh <- function(e) x <<- 1\ntryCatch(stop("a"), error = h)\nprint(x)'],
		['tryCatch finally and expr', 'x <- 0\ntryCatch(x <- 1, finally = x <- x + 10)\nprint(x)'],
		['on.exit after false', 'x <- 0\nf <- function() { on.exit(x <<- x + 1); on.exit(x <<- x * 10, add = TRUE, after = FALSE); NULL }\nf()\nprint(x)'],
		['on.exit digits param', 'f <- function() { op <- options(digits = 3); on.exit(options(op)); format(pi) }\nx <- f()\nprint(pi)'],
		['on.exit setwd', 'd <- getwd()\nf <- function() { on.exit(setwd(d)); setwd(tempdir()); 1 }\nx <- f()\nprint(basename(getwd()) == basename(d))'],
		['delayedAssign forced', 'delayedAssign("y", {x <<- 3; 4})\nx <- 1\nz <- y\nprint(x)'],
		['Find', 'x <- 0\nFind(function(i) { x <<- x + i; i > 1 }, 1:3)\nprint(x)'],
		['local envir', 'e <- new.env()\nlocal(y <- 5, envir = e)\nprint(e$y)'],
		['eval parse in function', 'x <- 0\nf <- function() eval(parse(text = "x <<- 4"))\nf()\nprint(x)'],
		['evalq expr call', 'x <- 1\nevalq(x <- 6)\nprint(x)'],
		['eval expression multi', 'eval(expression(a <- 3, b <- a * 2))\nprint(b)'],
		['Sys.setenv via sapply', 'sapply(1:2, function(i) Sys.setenv(A = "z"))\nprint(Sys.getenv("A"))'],
		['outer fun', 'x <- 0\nf <- function(a, b) { x <<- x + 1; a + b }\nouter(1:2, 1:2, f)\nprint(x)']
	];
	for(const [name, code, dropped] of cases) {
		assertSliceMatchesR(parser, name, code, { dropped });
	}
}));
